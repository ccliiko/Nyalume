import assert from 'node:assert/strict';
import {makeResolver,normalizePath,validateFiles} from '../cloud_service/static/pet-assets.mjs';
globalThis.location = {origin:'https://nyalume.example'};
assert.equal(normalizePath('角色\\贴图\\..\\贴图/脸.png'),'角色/贴图/脸.png');
assert.throws(()=>normalizePath('../../x'));
const notices=[];
const files=[{path:'角色/贴图/脸 #1.png',blob:new Blob(['texture'])}];
const resolver=makeResolver(files, text=>notices.push(text));
const url=resolver.resolve(resolver.localURL(files[0].path));
assert.ok(url.startsWith('blob:'));
assert.equal(resolver.resolve('/__petfiles/%E8%A7%92%E8%89%B2/贴图/脸 #1.png'),url);
assert.equal(await (await fetch(url)).text(),'texture');
assert.ok(resolver.resolve('http://169.254.169.254/latest/').startsWith('data:image/'));
assert.ok(resolver.resolve('/__petfiles/no.png').startsWith('data:image/'));
assert.equal(notices.length,2);
resolver.dispose();
await assert.rejects(fetch(url));
await assert.rejects(validateFiles([new File(['invalid'], 'x.pmx')]));
await validateFiles([new File(['PMX test'], '模型.pmx')]);
await assert.rejects(validateFiles([new File(['not-vmd'], 'x.vmd')],true));
console.log('PASS: Chinese/space/hash paths, Blob mapping/revocation, missing texture, blocked external paths and file validation');
